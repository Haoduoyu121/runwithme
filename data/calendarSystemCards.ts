export type SystemCardCategory =
  | "daily"
  | "monday"
  | "weekend"
  | "period-upcoming"
  | "period-active"
  | "period-ended";

export type SystemCardCharacter = "Levi" | "Erwin";

export type CalendarSystemCard = {
  id: string;
  character: SystemCardCharacter;
  category: SystemCardCategory;
  text: string;
  enabled: boolean;
};

function makeCards(
  character: SystemCardCharacter,
  category: SystemCardCategory,
  texts: string[]
): CalendarSystemCard[] {
  return texts.map((text, i) => ({
    id: `${character}-${category}-${i}`,
    character,
    category,
    text,
    enabled: true,
  }));
}

