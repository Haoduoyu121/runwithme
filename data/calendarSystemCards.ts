/* 纯随机抽一张（不看用户输入） */
export function pickSystemCard(
  category: SystemCardCategory
): CalendarSystemCard | null {
  const pool = SYSTEM_CARDS.filter(
    (c) => c.enabled && c.category === category
  );
  if (pool.length === 0) return null;
  return pool[Math.floor(Math.random() * pool.length)];
}